/**
 * bookingMeta.js — shared booking kind and creation-channel labels.
 * Recorded creation_context takes precedence over legacy origin values.
 *
 * Historically `origin` mixed two unrelated dimensions:
 *   - the CHANNEL a booking was created through (app / web / admin drawer), and
 *   - the KIND of record it is (a game seat, a membership calendar block).
 * Every page hardcoded its own option list, so filters offered options that
 * could never match that page's data (e.g. "Membership Program" on a table
 * that excludes program rows).
 *
 * This module splits origin into two orthogonal, filterable dimensions:
 *
 *   KIND — what the row IS:
 *     venue      → a paid venue/court booking
 *     event      → a seat in a hosted game / tournament (origin customer_game)
 *     membership → a membership-schedule calendar block (origin class_program;
 *                  informational, total 0 — NOT revenue)
 *
 *   CHANNEL — where it was created:
 *     marketplace   → the Bookboll marketplace (app or web checkout, and event
 *                     seats — events only exist on the marketplace)
 *     provider_site → a provider's own white-label website (origin
 *                     provider_site; recorded at checkout since this change —
 *                     older white-label bookings are indistinguishable from
 *                     marketplace web and stay under marketplace)
 *     manual        → created by staff in the admin dashboard
 *     auto          → generated by the system from a membership schedule
 *
 * Raw origin values seen in the DB:
 *   bookboll_app · bookboll_web · provider_site · manual_admin · manual (legacy
 *   seed) · customer_game · class_program
 *
 * Pages pass the option lists that fit THEIR data (see kindOptions /
 * channelOptions helpers) instead of hardcoding one generalized list.
 */

// ── classification ────────────────────────────────────────────────────────────
// Legacy skipped payments are provider-created calendar blocks for their own
// customers. Membership schedule rows are a different kind of calendar block.
export function isProviderSlotBlock(b) {
  return bookingKind(b) !== 'membership' && (b?.record_purpose === 'provider_slot_block' || b?.payment_method === 'payment_skipped' || b?.payment_status === 'skipped')
}
export function isCommercialBooking(b) {
  return bookingKind(b) !== 'membership' && !isProviderSlotBlock(b) && !['cancelled','canceled'].includes(b?.booking_status)
}
export function bookingKind(b) {
  const o = b?.origin || ''
  if (o === 'class_program') return 'membership'
  if (o === 'customer_game') return 'event'
  return 'venue'
}

export function bookingChannel(b) {
  const recorded = b?.creation_context?.channel
  if (recorded) return ({ admin:'manual', site:'provider_site' })[recorded] || recorded
  const o = b?.origin || ''
  if (isProviderSlotBlock(b)) return 'manual'
  if (o === 'provider_site') return 'provider_site'
  if (o === 'manual_admin' || o === 'manual') return 'manual'
  if (o === 'class_program') return 'auto'
  return ['bookboll_app','bookboll_web','customer_game'].includes(o) ? 'marketplace' : 'unknown'
}

// ── option lists (value = the derived dimension, not raw origin) ─────────────
export const KIND_LABELS = {
  venue: 'Venue booking',
  event: 'Event / game',
  membership: 'Membership session',
}
export const CHANNEL_LABELS = {
  marketplace: 'Bookboll marketplace',
  provider_site: 'Provider website',
  manual: 'Admin created (manual)',
  auto: 'Auto — membership schedule',
  unknown: 'Source not recorded',
}

/** Build option arrays for a page. Pass only the values that can actually occur
 *  in that page's data — a filter option that can never match is a bug. */
export function kindOptions(values = ['venue', 'event', 'membership']) {
  return values.map(v => ({ value: v, label: KIND_LABELS[v] || v }))
}
export function channelOptions(values = ['marketplace', 'provider_site', 'manual', 'unknown']) {
  return values.map(v => ({ value: v, label: CHANNEL_LABELS[v] || v }))
}

// ── filter predicates (multi-select semantics: empty selection = no filter) ──
export function matchKind(b, selected) {
  return !selected?.length || selected.includes(bookingKind(b))
}
export function matchChannel(b, selected) {
  return !selected?.length || selected.includes(bookingChannel(b))
}

// ── display helpers ──────────────────────────────────────────────────────────
export function kindLabel(b) { return KIND_LABELS[bookingKind(b)] || '' }
export function channelLabel(b) {
  // Short badge text: the derived channel, with app/web detail where we have it.
  const o = b?.origin || ''
  if (bookingChannel(b) === 'marketplace' && o === 'bookboll_app') return 'Bookboll app'
  if (bookingChannel(b) === 'marketplace' && o === 'bookboll_web') return 'Bookboll web'
  return CHANNEL_LABELS[bookingChannel(b)] || ''
}

export function bookingCreatorLabel(b) {
  const c = b?.creation_context
  if (c?.actor_kind === 'system') return 'System'
  return c?.actor_name || (b?.created_by ? `Recorded user #${b.created_by}` : 'Creator not recorded')
}
